/**
 * ILLUSTRATIVE DEMO DATA for the map search. Every business below is invented: the names are made
 * up, every website uses the reserved `.example` domain, and the website findings are written by
 * hand to look like what the real validators (src/lib/qualification/website-validator.ts) report.
 * Only the map coordinates are real places in South Delhi, so the pins sit on real streets.
 * Never replace these with real business names: the app would then make claims about real websites.
 */
import { z } from "zod";
import { LOCALITY_NAMES, isInsideArea, type LatLng, type LocalityName } from "./area";

/** What a website check "found". Mirrors the order the real validator runs its checks. */
const siteSchema = z.discriminatedUnion("status", [
  /** The listing has no website at all. */
  z.object({ status: z.literal("none") }),
  /** robots.txt asks bots not to check the site, so nothing else runs. */
  z.object({ status: z.literal("robots-blocked") }),
  /** The site timed out or the address did not resolve. */
  z.object({ status: z.literal("unreachable") }),
  /** The homepage answered with an error code, so nothing else runs. */
  z.object({ status: z.literal("http-error"), code: z.number().int().min(400).max(599) }),
  z.object({
    status: z.literal("loads"),
    mobileFriendly: z.boolean(),
    contact: z.enum(["form", "link", "missing"]),
    copyrightYear: z.number().int().min(2000).max(2026).optional(),
    brokenPage: z.object({ path: z.string().regex(/^[a-z-]+$/), code: z.number().int() }).optional(),
    /** PageSpeed mobile score, 0-100. */
    mobileSpeed: z.number().int().min(0).max(100).optional(),
  }),
]);

export const businessSchema = z.object({
  id: z.string().regex(/^[a-z0-9-]+$/),
  name: z.string().min(2),
  category: z.string().min(2),
  locality: z.enum(LOCALITY_NAMES as [LocalityName, ...LocalityName[]]),
  position: z.tuple([z.number(), z.number()]).refine((point) => isInsideArea(point as LatLng), "Pin must sit inside the search area"),
  website: z.string().url().endsWith(".example").nullable(),
  /** When the map listing was last updated. */
  listedAt: z.iso.datetime({ offset: true }),
  description: z.string().min(10),
  site: siteSchema,
});

export type DemoBusiness = z.infer<typeof businessSchema>;
export type DemoSite = z.infer<typeof siteSchema>;

